# ============================================================
# 函数 1：lcp_len（你需要写的）
# ============================================================
# 作用：计算两个字符串的最长公共前缀长度。
#       流式输出时，模型每次返回完整回复文本，但之前已发送过一部分，
#       用这个函数算出"新增部分"的起始位置，避免重复发送。
#
# 示例：
#   lcp_len("你好世界", "你好世界，今天天气不错") → 4 ("你好世界" 已发送)
#   lcp_len("abc", "xyz") → 0 (完全不同)
#
# 自己写，别偷看答案 ↓↓↓


def lcp_len(a: str, b: str) -> int:
    """返回 a 和 b 的最长公共前缀长度"""
    # NOTE: 遍历 zip(a, b)，逐字符比较，遇到不同就 break
    i = 0
    for ca,cb in zip(a, b):
        if ca != cb:
            break
        i+=1
    return i
